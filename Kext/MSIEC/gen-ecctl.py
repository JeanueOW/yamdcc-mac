#!/usr/bin/env python3
"""Generate the MSIEC helper SSDT and its hashes.

The helper lives inside the firmware's SCM0 device and only adds AML
wrappers around the EC byte fields. Every write goes through an ACPI method,
so AppleACPIEC performs the EC transaction and holds the EC lock. Methods
never touch ports directly.

Registers already declared by the firmware DSDT (0x68..0x79, 0x80..0x90,
0xA0..0xBF, 0xC8..0xCD, 0xD0..0xD6, 0xE8) are written through their existing
field names. Registers missing from the DSDT (0x7A..0x7F CPU down thresholds,
0x92..0x98 GPU down thresholds + full blast, 0xD7 charge limit) get private
fields inside this SSDT, at the same EC offsets.
"""

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Registers used by the fan controller, split by where the field is declared.
EXISTING = (
    [0x6A + i for i in range(6)]      # CPU up thresholds
    + [0x72 + i for i in range(7)]    # CPU fan curve
    + [0x82 + i for i in range(6)]    # GPU up thresholds
    + [0x8A + i for i in range(7)]    # GPU fan curve
    + [0xD2, 0xD3, 0xD4, 0xE8]
)
# Declared in the helper SSDT: absent from the firmware DSDT field list, which
# jumps from 0x79 to 0x80 and skips 0x91..0x9F and 0xD7 entirely.
PRIVATE_GROUPS = [(0x7A, 6), (0x92, 7), (0xD7, 1)]
PRIVATE = [reg + i for reg, count in PRIVATE_GROUPS for i in range(count)]


def field_name(reg: int, new_style: bool) -> str:
    return f"Z{reg:02X}" if new_style else f"TD{reg:02X}"


def methods():
    lines = []
    for reg in EXISTING:
        lines.append(f"        Method (YW{reg:02X}, 1, Serialized)")
        lines.append("        {")
        lines.append(f"            Store (Arg0, {field_name(reg, False)})")
        lines.append("            Return (One)")
        lines.append("        }")
    for reg in PRIVATE:
        lines.append(f"        Method (YW{reg:02X}, 1, Serialized)")
        lines.append("        {")
        lines.append(f"            Store (Arg0, {field_name(reg, True)})")
        lines.append("            Return (One)")
        lines.append("        }")
        lines.append(f"        Method (YR{reg:02X}, 0, Serialized)")
        lines.append("        {")
        lines.append(f"            Return ({field_name(reg, True)})")
        lines.append("        }")
    return lines


def asl() -> str:
    out = [
        "/* Generated by gen-ecctl.py — do not edit by hand. */",
        'DefinitionBlock ("", "SSDT", 2, "YAMDCC", "ECCTL", 0x00000001)',
        "{",
        "    External (_SB_.PC00.LPCB.EC_, DeviceObj)",
        "    External (_SB_.PC00.LPCB.EC_.SCM0, DeviceObj)",
        "",
        "    Scope (\\_SB.PC00.LPCB.EC.SCM0)",
        "    {",
    ]
    for index, (base, count) in enumerate(PRIVATE_GROUPS, start=1):
        names = [field_name(base + i, True) for i in range(count)]
        out.append(f"        OperationRegion (YEC{index}, EmbeddedControl, 0x{base:02X}, 0x{count:02X})")
        out.append(f"        Field (YEC{index}, ByteAcc, NoLock, Preserve)")
        out.append("        {")
        out.append("            " + ", ".join(f"{n}, 8" for n in names) + ",")
        out.append("        }")
    out.extend(methods())
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def fnv1a64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main() -> int:
    source = HERE / "MSIEC-ECCTL.dsl"
    source.write_text(asl(), encoding="utf-8")

    iasl = HERE.parent.parent / "build" / "tools" / "acpica-20260930" / "generate" / "unix" / "bin" / "iasl"
    if not iasl.exists():
        iasl = Path("/usr/local/bin/iasl")
    result = subprocess.run(
        [str(iasl), "-p", str(HERE / "MSIEC-ECCTL.aml"), "-f", str(source)],
        capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        return result.returncode

    aml = (HERE / "MSIEC-ECCTL.aml").read_bytes()
    print(f"AML {len(aml)} bytes  FNV1a64 0x{fnv1a64(aml):016X}  sha256 ", end="")
    import hashlib
    print(hashlib.sha256(aml).hexdigest())
    print("Registers: existing", len(EXISTING), "private", len(PRIVATE),
          "methods", len(EXISTING) + 2 * len(PRIVATE))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
